const { test } = require('node:test');
const assert = require('node:assert/strict');
const { randomUUID } = require('node:crypto');
const fs = require('node:fs/promises'), os = require('node:os'), path = require('node:path');
const { ConfigService } = require('@nestjs/config');
const { AutomaticMessagesService, renderTemplate } = require('../dist/automatic-messages/automatic-messages.module');
const { DomainEvents } = require('../dist/events/domain-events');
const { WhatsappAttendanceService } = require('../dist/whatsapp-conversations/whatsapp-attendance.service');
const { ConversationMessageRecordsService } = require('../dist/whatsapp-conversations/conversation-message-records.service');
const { conversationsFixture } = require('./helpers/conversations-fixture.cjs');
const status = code => error => error.getStatus?.() === code;
test('automatic models persist independently, check versions and unknown variables, and never enable dispatch', async t => {
  const directory = await fs.mkdtemp(path.join(os.tmpdir(), 'wg-models-'));
  t.after(() => fs.rm(directory, { recursive: true, force: true }));
  const config = new ConfigService({ APP_SETTINGS_DIRECTORY: directory }), events = new DomainEvents();
  const service = new AutomaticMessagesService(config, events); service.onModuleInit(); t.after(() => service.onModuleDestroy());
  const defaults = (await service.list()).templates;
  assert.equal(defaults.length, 4); assert.ok(defaults.every(model => !model.isActive));
  const original = defaults[1], dto = { ...original, isActive: true };
  const saved = await service.save(dto, original.id);
  assert.equal(saved.version, 2);
  await assert.rejects(service.save(dto, original.id), status(409));
  await assert.rejects(service.remove(saved.id, saved.version), status(409));
  assert.throws(() => renderTemplate('Olá {senha}', 'Maria'), status(400));
  assert.equal(renderTemplate('{atendente} / {atendente}', '$&'), '$& / $&');
  const event = { type: 'attendance.changed', automaticEvent: 'started', transitionKey: 'same-transition' };
  events.emit(event); events.emit(event); events.emit({ type: 'connection.changed' });
  const result = await service.list(); assert.equal(result.dispatchEnabled, false); assert.equal(result.recentEvents.length, 1);
  const restarted = new AutomaticMessagesService(config, events);
  assert.equal((await restarted.list()).templates.find(item => item.id === saved.id).isActive, true);
});
test('attendance owner can transfer; another attendant cannot; repeated transfer never emits duplicate automatic events', async t => {
  const f = await conversationsFixture(t), events = new DomainEvents(), observed = [];
  events.subscribe(event => observed.push(event));
  const service = new WhatsappAttendanceService(f.database, events);
  await service.claim(f.conversation.id, f.regular.id);
  await assert.rejects(service.assign(f.conversation.id, f.other.id, f.other.id), status(403));
  await service.assign(f.conversation.id, f.regular.id, f.other.id);
  await assert.rejects(service.assign(f.conversation.id, f.other.id, f.other.id), status(409));
  assert.deepEqual(observed.map(event => event.automaticEvent), ['started', 'transferred']);
});
test('waiting automatic event only follows a new live direct message; replay, history and own messages cannot trigger it', async t => {
  const f = await conversationsFixture(t), events = new DomainEvents(), observed = [];
  events.subscribe(event => observed.push(event));
  const records = new ConversationMessageRecordsService(f.database, events);
  const input = { connectionId: f.connectionId, remoteJid: randomUUID() + '@lid', whatsappMessageId: 'new-live', fromMe: false, origin: 'live', messageTimestamp: new Date() };
  await records.record(input); await records.record(input);
  await records.record({ ...input, remoteJid: randomUUID() + '@lid', whatsappMessageId: 'history', origin: 'history' });
  await records.record({ ...input, remoteJid: randomUUID() + '@lid', whatsappMessageId: 'own', fromMe: true });
  assert.equal(observed.length, 1); assert.equal(observed[0].automaticEvent, 'waiting');
});
